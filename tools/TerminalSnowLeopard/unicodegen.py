"""Generate compact C tables from Unicode 5.1's published UCD files.

Inputs: https://www.unicode.org/Public/5.1.0/ucd/
The generated data is covered by UNICODE-LICENSE.txt.
"""
import argparse
import hashlib
from pathlib import Path

CATEGORIES = 'Cn Lu Ll Lt Lm Lo Mn Me Mc Nd Nl No Zs Zl Zp Cc Cf Co Cs Pd Ps Pe Pc Po Sm Sc Sk So Pi Pf'.split()
WIDTHS = 'N A H F Na W'.split()


def generate(directory, output):
    names = ('UnicodeData.txt', 'EastAsianWidth.txt', 'BidiMirroring.txt', 'CompositionExclusions.txt')
    files = {name: (directory / name).read_bytes() for name in names}
    def rows(name):
        for line in files[name].decode('utf-8').splitlines():
            value = line.split('#', 1)[0].strip()
            if value:
                yield [item.strip() for item in value.split(';')]
    properties = [0] * 0x110000
    decompositions = []
    combining = {}
    first = None
    for row in rows('UnicodeData.txt'):
        code = int(row[0], 16)
        category, ccc, mirrored = CATEGORIES.index(row[2]), int(row[3]), row[9] == 'Y'
        if row[1].endswith(', First>'):
            first = code
            continue
        start = first if row[1].endswith(', Last>') else code
        first = None
        properties[start:code+1] = [category | ccc << 8 | mirrored << 24] * (code+1-start)
        if ccc:
            combining[code] = ccc
        if row[5]:
            parts = row[5].split()
            compatibility = parts[0].startswith('<')
            if compatibility:
                parts = parts[1:]
            decompositions.append((code, compatibility, [int(v, 16) for v in parts]))
    for row in rows('EastAsianWidth.txt'):
        bounds = [int(v, 16) for v in row[0].split('..')]
        for code in range(bounds[0], bounds[-1]+1):
            properties[code] |= WIDTHS.index(row[1]) << 16
    excluded = {int(row[0], 16) for row in rows('CompositionExclusions.txt')}
    compositions = sorted((parts[0], parts[1], code) for code, compat, parts in decompositions
                          if not compat and len(parts) == 2 and code not in excluded
                          and not combining.get(parts[0]))
    lines = ['/* Generated by unicodegen.py from Unicode 5.1.0. See UNICODE-LICENSE.txt.']
    lines += [' * %s SHA-256 %s' % (name, hashlib.sha256(files[name]).hexdigest()) for name in names]
    lines += [' */', 'static const struct { unsigned first, last, value; } snowUnicodeProperties[] = {']
    start = 0
    for code in range(1, len(properties)+1):
        if code == len(properties) or properties[code] != properties[start]:
            if properties[start]:
                lines.append('{0x%x,0x%x,0x%x},' % (start, code-1, properties[start]))
            start = code
    lines += ['};', 'static const struct { unsigned code, mirror; } snowUnicodeMirrors[] = {']
    lines += ['{0x%s,0x%s},' % tuple(row[:2]) for row in rows('BidiMirroring.txt')]
    lines += ['};', 'static const struct { unsigned first, second, composed; } snowUnicodeCompositions[] = {']
    lines += ['{0x%x,0x%x,0x%x},' % row for row in compositions]
    lines += ['};', 'static const struct SnowUnicodeDecomposition { unsigned code, offset; unsigned char count, compatibility; } snowUnicodeDecompositions[] = {']
    points = []
    for code, compat, parts in decompositions:
        lines.append('{0x%x,%d,%d,%d},' % (code, len(points), len(parts), compat))
        points.extend(parts)
    lines += ['};', 'static const unsigned snowUnicodeDecomposedPoints[] = {']
    lines += [','.join('0x%x' % point for point in points[i:i+12])+',' for i in range(0, len(points), 12)]
    trails = [0 if v < 0xc0 else 1 if v < 0xe0 else 2 if v < 0xf0 else 3 if v < 0xf8 else 4 if v < 0xfc else 5 if v < 0xfe else 0 for v in range(256)]
    lines += ['};', 'const unsigned char utf8_countTrailBytes[256] = {']
    lines += [','.join(map(str, trails[i:i+32]))+',' for i in range(0, 256, 32)]
    lines += ['};', '']
    output.write_text('\n'.join(lines), encoding='ascii', newline='\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('directory', type=Path)
    parser.add_argument('output', type=Path)
    arguments = parser.parse_args()
    generate(arguments.directory, arguments.output)
